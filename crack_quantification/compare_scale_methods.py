"""
compare_scale_methods.py
========================

Benchmark the 4 automatic scale-recovery approaches on synthetic scenes with
KNOWN ground-truth mm/pixel:

  Method 1: Camera metadata / intrinsics (EXIF + known distance)
  Method 2: Camera distance estimation (+ intrinsics)
  Method 3: Monocular depth estimation (plane fit + pinhole)
  Method 4: Fusion (inverse-variance weighted combination)

Each scene is generated by simulating a camera with:
  - a chosen focal length, sensor width, image resolution
  - a perpendicular distance to a flat wall
  - a synthetic crack of known physical size (in mm)

The true mm/pixel is computed from the pinhole model. Each method estimates
the scale from (possibly noisy / partial) observations, and we compare the
estimated crack length vs the true length.

Run:
    python -m crack_quantification.compare_scale_methods
"""

import numpy as np

from .scale_recovery import (
    scale_from_metadata,
    scale_from_camera_distance,
    scale_from_depth_map,
    fuse_scales,
    mm_per_px_from_geometry,
)


# --------------------------------------------------------------------------- #
# Synthetic scene generation
# --------------------------------------------------------------------------- #
def make_scene(
    focal_length_mm=24.0,
    sensor_width_mm=36.0,
    image_width_px=1280,
    distance_mm=2000.0,
    true_crack_length_mm=100.0,
):
    """Simulate a camera looking at a flat wall with a known-size crack."""
    true_mmpp = mm_per_px_from_geometry(
        focal_length_mm, sensor_width_mm, image_width_px, distance_mm
    )
    # Crack length in pixels (true)
    crack_px = true_crack_length_mm / true_mmpp

    # Synthetic depth map of a flat wall at `distance_mm` (with a bit of noise)
    h = int(image_width_px * 0.75)
    w = image_width_px
    depth = np.full((h, w), distance_mm, dtype=np.float64)
    depth += np.random.normal(0, distance_mm * 0.02, depth.shape)

    # Focal length in pixels
    focal_px = focal_length_mm / sensor_width_mm * image_width_px

    scene = {
        "focal_length_mm": focal_length_mm,
        "sensor_width_mm": sensor_width_mm,
        "image_width_px": image_width_px,
        "distance_mm": distance_mm,
        "true_crack_length_mm": true_crack_length_mm,
        "crack_px": crack_px,
        "true_mmpp": true_mmpp,
        "depth_map": depth,
        "focal_px": focal_px,
        "exif": {
            "FocalLength": (int(focal_length_mm), 1),
            "SensorWidth": sensor_width_mm,
            "PixelXDimension": image_width_px,
        },
    }
    return scene


# --------------------------------------------------------------------------- #
# Method estimators (each returns (mm_per_px, std) or raises)
# --------------------------------------------------------------------------- #
def est_metadata(scene, noise_scale=0.0):
    """Method 1: metadata + known distance, with optional distance noise."""
    dist = scene["distance_mm"] * (1.0 + noise_scale * np.random.randn())
    cal = scale_from_metadata(
        scene["exif"],
        distance_mm=dist,
    )
    return cal.mm_per_px, abs(dist - scene["distance_mm"]) * (
        scene["true_mmpp"] / scene["distance_mm"]
    )


def est_camera_distance(scene, noise_scale=0.0):
    """Method 2: estimated camera distance + intrinsics, with distance noise."""
    dist = scene["distance_mm"] * (1.0 + noise_scale * np.random.randn())
    cal = scale_from_camera_distance(
        dist,
        focal_length_mm=scene["focal_length_mm"],
        sensor_width_mm=scene["sensor_width_mm"],
        image_width_px=scene["image_width_px"],
    )
    return cal.mm_per_px, abs(dist - scene["distance_mm"]) * (
        scene["true_mmpp"] / scene["distance_mm"]
    )


def est_depth(scene, noise_scale=0.0):
    """Method 3: monocular depth plane fit + pinhole."""
    depth = scene["depth_map"] * (1.0 + noise_scale * np.random.randn())
    cal = scale_from_depth_map(
        depth,
        focal_length_px=scene["focal_px"],
        sensor_width_mm=scene["sensor_width_mm"],
        image_width_px=scene["image_width_px"],
        metric=True,
    )
    # std proportional to depth noise
    std = scene["true_mmpp"] * noise_scale
    return cal.mm_per_px, std


def est_fusion(scene, noise_scales=(0.0, 0.0, 0.0)):
    """Method 4: fuse the three estimates."""
    ests = []
    for fn, ns in [
        (est_metadata, noise_scales[0]),
        (est_camera_distance, noise_scales[1]),
        (est_depth, noise_scales[2]),
    ]:
        try:
            val, std = fn(scene, noise_scale=ns)
            ests.append({"mm_per_px": val, "std_mm_per_px": max(std, 1e-9)})
        except Exception:
            pass
    cal = fuse_scales(ests)
    return cal.mm_per_px


# --------------------------------------------------------------------------- #
# Benchmark
# --------------------------------------------------------------------------- #
def run_benchmark(n_scenes=40, noise_scale=0.05):
    np.random.seed(42)
    results = {
        name: []
        for name in ["metadata", "camera_distance", "depth", "fusion"]
    }

    for _ in range(n_scenes):
        # Randomize camera parameters
        foc = float(np.random.uniform(18, 70))
        sensor = float(np.random.uniform(6, 36))
        width = int(np.random.choice([640, 1280, 1920]))
        dist = float(np.random.uniform(500, 5000))
        true_len_mm = float(np.random.uniform(20, 300))

        scene = make_scene(
            focal_length_mm=foc,
            sensor_width_mm=sensor,
            image_width_px=width,
            distance_mm=dist,
            true_crack_length_mm=true_len_mm,
        )

        crack_px = scene["crack_px"]
        true_mmpp = scene["true_mmpp"]

        # Compare estimated crack length = crack_px * estimated_mmpp
        try:
            mmpp, _ = est_metadata(scene, noise_scale=noise_scale)
            results["metadata"].append(abs(crack_px * mmpp - true_len_mm))
        except Exception:
            pass

        try:
            mmpp, _ = est_camera_distance(scene, noise_scale=noise_scale)
            results["camera_distance"].append(abs(crack_px * mmpp - true_len_mm))
        except Exception:
            pass

        try:
            mmpp, _ = est_depth(scene, noise_scale=noise_scale)
            results["depth"].append(abs(crack_px * mmpp - true_len_mm))
        except Exception:
            pass

        try:
            mmpp = est_fusion(
                scene,
                noise_scales=(noise_scale, noise_scale, noise_scale),
            )
            results["fusion"].append(abs(crack_px * mmpp - true_len_mm))
        except Exception:
            pass

    print("\n" + "=" * 72)
    print("SCALE-RECOVERY METHOD COMPARISON (synthetic scenes with true mm/px)")
    print("=" * 72)
    print(
        f"Scenes: {n_scenes}   Noise level: +/-{noise_scale * 100:.0f}% "
        f"per observation\n"
    )
    print(f"{'Method':<18}{'Mean abs err':>16}{'Rel err %':>14}{'Std dev':>14}")
    print("-" * 72)

    summary = {}
    for name, errs in results.items():
        if not errs:
            continue
        mean_err = float(np.mean(errs))
        rel_err = mean_err / 100.0 * 100  # approx normalized to ~100mm cracks
        std = float(np.std(errs))
        summary[name] = {"mean_abs": mean_err, "std": std}
        print(f"{name:<18}{mean_err:>16.3f}{rel_err:>14.2f}{std:>14.3f}")

    print("-" * 72)
    # Rank by mean absolute error
    ranking = sorted(summary.items(), key=lambda kv: kv[1]["mean_abs"])
    print("\nRanking (lower mean abs error is better):")
    for i, (name, s) in enumerate(ranking, 1):
        print(f"  {i}. {name:<18} mean abs err = {s['mean_abs']:.3f} mm")
    print("\n✅ Benchmark complete.")
    return summary


if __name__ == "__main__":
    run_benchmark()
